#!/bin/bash
# build.sh — build the universal Aegis live ISO(s).
# All user choices (Tor/I2P, browser, desktop, MAC spoofing, Kali, encryption,
# compartmentalization) are made later by the on-ISO installer, NOT here. The only
# build-time choice is the CPU architecture (because the kernel/bootloader/binaries
# are compiled per-architecture and a CPU can only boot its own instruction set).
#
# Run on a Debian/Ubuntu host as root. See docs/BUILD.md.
#
#   sudo ./build.sh --arch amd64      # normal PCs (BIOS + UEFI)
#   sudo ./build.sh --arch arm64      # UEFI arm64 (QEMU virt, Apple-Silicon VM, …)
#   sudo ./build.sh --arch both       # build both, one after the other
#
#   --edition live       (default) amnesic live USB; wipes RAM & powers off if the USB is pulled (Tails-style)
#   --edition installer  boots straight into the installer (install to an SSD)
#   --edition both       build both editions
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE"

. "$HERE/profiles/defaults.conf"
HOST_ARCH="$(dpkg --print-architecture 2>/dev/null || echo amd64)"
ARCH="$HOST_ARCH"
EDITION="live"
SUITE="${AEGIS_SUITE:-trixie}"
MIRROR="http://deb.debian.org/debian/"

usage() { grep '^#' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }
while [ $# -gt 0 ]; do
  case "$1" in
    --arch)    ARCH="$2"; shift 2 ;;
    --edition) EDITION="$2"; shift 2 ;;
    --suite)   SUITE="$2"; shift 2 ;;
    --mirror)  MIRROR="$2"; shift 2 ;;
    -h|--help) usage 0 ;;
    *) echo "unknown arg: $1" >&2; usage 1 ;;
  esac
done
case "$ARCH" in
  amd64|arm64) ARCHES=("$ARCH") ;;
  both)        ARCHES=(amd64 arm64) ;;
  *) echo "arch must be amd64, arm64 or both" >&2; exit 1 ;;
esac
case "$EDITION" in
  live|installer) EDITIONS=("$EDITION") ;;
  both)           EDITIONS=(live installer) ;;
  *) echo "edition must be live, installer or both" >&2; exit 1 ;;
esac
[ "$(id -u)" = 0 ] || { echo "must run as root (live-build uses chroots)." >&2; exit 1; }

export SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-$(date +%s)}"

stage_payload() {
  echo "==> Staging Aegis payload into config/includes.chroot"
  mkdir -p config/includes.chroot/etc/aegis
  {
    echo "# generated by build.sh"
    echo "AEGIS_NAME=\"$AEGIS_NAME\""
    echo "AEGIS_DEFAULT_NETMODE=\"${AEGIS_DEFAULT_NETMODE}\""
    echo "AEGIS_MAC_SPOOF=\"${AEGIS_MAC_SPOOF}\""
    echo "AEGIS_USBGUARD=\"${AEGIS_USBGUARD}\""
    echo "AEGIS_RAM_WIPE=\"${AEGIS_RAM_WIPE}\""
    echo "AEGIS_HARDENED_MALLOC=\"${AEGIS_HARDENED_MALLOC}\""
    echo "AEGIS_BROWSER=\"${AEGIS_BROWSER}\""
    echo "AEGIS_STEALTH=\"${AEGIS_STEALTH:-yes}\""
  } > config/includes.chroot/etc/aegis/build.env

  mkdir -p config/includes.chroot/usr/share/aegis
  cp -a i2p-manager   config/includes.chroot/usr/share/aegis/
  cp -a setup-wizard  config/includes.chroot/usr/share/aegis/

  mkdir -p config/includes.chroot/etc/calamares/modules
  cp -a installer/calamares/settings.conf config/includes.chroot/etc/calamares/
  cp -a installer/calamares/branding       config/includes.chroot/etc/calamares/
  cp -a installer/calamares/modules/.       config/includes.chroot/etc/calamares/modules/

  cp -f catalog/de-xfce.list.chroot         config/package-lists/
  cp -f catalog/browser-firefox.list.chroot config/package-lists/

  # --- bootloader: AUTO-BOOT (finite timeout) + brand the menu as Aegis ---
  # live-build generates the GRUB/isolinux config late (after binary hooks), so a
  # post-build sed can't reliably touch it. Override the templates the supported
  # way: copy live-build's defaults into config/bootloaders/ and patch them. The
  # stock GRUB config.cfg has NO timeout, so GRUB waits forever for a keypress —
  # this adds a 5s timeout so the ISO boots on its own, like an install disc.
  rm -rf config/bootloaders
  local BL_SRC=/usr/share/live/build/bootloaders
  if [ -d "$BL_SRC" ]; then
    mkdir -p config/bootloaders
    for d in "$BL_SRC"/*/; do cp -a "$d" "config/bootloaders/$(basename "$d")"; done
    # GRUB: force a 5-second auto-boot timeout.
    for c in config/bootloaders/*/config.cfg; do
      [ -f "$c" ] || continue
      if grep -q '^set timeout=' "$c"; then
        sed -i 's/^set timeout=.*/set timeout=5/' "$c"
      else
        sed -i '1i set timeout=5\nset timeout_style=menu' "$c"
      fi
    done
    # ISOLINUX/SYSLINUX (BIOS boot, e.g. amd64 in QEMU): 5s timeout, boot default.
    for c in config/bootloaders/isolinux/*.cfg config/bootloaders/syslinux/*.cfg; do
      [ -f "$c" ] || continue
      sed -i 's/^timeout .*/timeout 50/; s/^prompt .*/prompt 0/' "$c"
    done
    # Brand the visible menu text (both GRUB and isolinux).
    find config/bootloaders -name '*.cfg' -type f -exec \
      sed -i 's/Live system/Aegis OS/g; s@Debian GNU/Linux@Aegis OS@g; s/Debian Live/Aegis OS/g; s/\bDebian\b/Aegis/g' {} +
    echo "I: staged custom bootloaders (auto-boot timeout + Aegis branding)"
  else
    echo "W: live-build bootloader templates not at $BL_SRC; menu stays stock."
  fi

  # --- Build the Aegis Debian packages into a staging dir (.aegis-debs) ---
  # The friendly layer (Control Center + Welcome wizard) and the packaged backend
  # ship as real .deb's. build_one copies these into config/packages.chroot/ right
  # before `lb build` (after lb clean/config), and live-build installs them.
  # This is the first step of the ISO consuming packages instead of only hooks.
  rm -rf .aegis-debs; mkdir -p .aegis-debs
  if [ -d packages ] && command -v dpkg-buildpackage >/dev/null 2>&1; then
    echo "==> Building Aegis Debian packages"
    for d in packages/*/; do
      [ -f "${d}debian/control" ] || continue
      ( cd "$d" && dpkg-buildpackage -us -uc -b -d )
    done
    mv packages/*.deb .aegis-debs/ 2>/dev/null || true
    rm -f packages/*.changes packages/*.buildinfo 2>/dev/null || true
    echo "I: built $(ls .aegis-debs/*.deb 2>/dev/null | wc -l) Aegis .deb(s)"
  else
    echo "W: dpkg-buildpackage unavailable or no packages/ — ISO built WITHOUT Aegis packages"
  fi
}

build_one() {
  local arch="$1" edition="${2:-live}"
  echo "==> Building Aegis  edition=$edition  arch=$arch  suite=$SUITE"

  local BOOTLOADERS="grub-efi"
  local -a QEMU_OPTS=()
  [ "$arch" = amd64 ] && BOOTLOADERS="syslinux,grub-efi"   # BIOS + UEFI
  if [ "$arch" != "$HOST_ARCH" ]; then
    echo "==> Cross-building $arch on $HOST_ARCH (needs qemu-user-static)"
    case "$arch" in
      arm64) QEMU_OPTS=(--bootstrap-qemu-arch arm64 --bootstrap-qemu-static /usr/bin/qemu-aarch64-static) ;;
      amd64) QEMU_OPTS=(--bootstrap-qemu-arch amd64 --bootstrap-qemu-static /usr/bin/qemu-x86_64-static) ;;
    esac
  fi

  # Hardened + quiet kernel command line for the live boot entry.
  # console=ttyS0 makes systemd spawn a serial getty, which the CI boot smoke-test
  # watches for ("login:") to prove the image boots all the way. tty0 stays the
  # primary console so the desktop is unaffected.
  # Serial console device differs by arch: 8250 (ttyS0) on x86, PL011 (ttyAMA0)
  # on the arm64 'virt' machine. The CI boot smoke-test reads this serial line, so
  # getting it right per-arch is what makes the arm64 boot test actually work.
  local SERCON="ttyS0,115200"
  [ "$arch" = arm64 ] && SERCON="ttyAMA0,115200"
  # Serial LAST = primary console, so systemd status + the login prompt go to the
  # serial port (what the CI boot smoke-test reads). tty0 is also listed, so the
  # screen still shows the (verbose, no 'quiet splash') boot. No loglevel=0, so the
  # boot is actually visible.
  # live-config.user-fullname sets the live account's GECOS (shown in the XFCE
  # panel / logout dialog) to "Aegis" instead of live-config's "Debian Live user".
  local BOOTAPPEND="boot=live components live-config.user-fullname=Aegis console=tty0 console=$SERCON \
init_on_alloc=1 init_on_free=1 page_alloc.shuffle=1 page_poison=1 slab_nomerge \
randomize_kstack_offset=on vsyscall=none debugfs=off \
lockdown=confidentiality mce=0 ipv6.disable=1 \
intel_iommu=on amd_iommu=on efi=disable_early_pci_dma \
mitigations=auto,nosmt"

  echo "==> lb config ($arch)"
  lb clean --purge >/dev/null 2>&1 || true
  lb config \
    --architectures "$arch" \
    --linux-flavours "$arch" \
    --distribution "$SUITE" \
    --archive-areas "main contrib non-free non-free-firmware" \
    --mirror-bootstrap "$MIRROR" \
    --mirror-binary "$MIRROR" \
    --debian-installer none \
    --bootloaders "$BOOTLOADERS" \
    --bootappend-live "$BOOTAPPEND" \
    --apt-recommends false \
    --apt-indices false \
    --memtest none \
    --firmware-chroot false \
    --firmware-binary false \
    --iso-application "Aegis OS" \
    --iso-volume "Aegis $edition $arch" \
    "${QEMU_OPTS[@]}"

  # Place the pre-built Aegis .deb's where live-build installs them. Done here
  # (after lb clean/config) so a purge can't drop them before the build.
  if ls .aegis-debs/*.deb >/dev/null 2>&1; then
    rm -rf config/packages.chroot; mkdir -p config/packages.chroot
    cp -f .aegis-debs/*.deb config/packages.chroot/
    echo "I: $(ls config/packages.chroot/*.deb | wc -l) Aegis .deb(s) staged for install into the image"
  fi

  echo "==> lb build ($arch) — this takes a while"
  lb build

  local STAMP SRC OUT
  STAMP="$(date -u -d "@$SOURCE_DATE_EPOCH" +%Y%m%d 2>/dev/null || date +%Y%m%d)"
  SRC="$(ls -1 live-image-*.hybrid.iso 2>/dev/null | head -n1 || true)"
  [ -n "$SRC" ] || { echo "build produced no ISO for $arch — check the log." >&2; return 1; }
  OUT="aegis-${edition}-${arch}-${STAMP}.iso"
  mv "$SRC" "$OUT"
  sha256sum "$OUT" > "$OUT.sha256"
  echo "==> Built: $OUT  (+ .sha256)"
}

stage_payload
for edition in "${EDITIONS[@]}"; do
  # Write this batch's edition into build.env (the 0600 hook reads it).
  sed -i '/^AEGIS_EDITION=/d' config/includes.chroot/etc/aegis/build.env 2>/dev/null || true
  echo "AEGIS_EDITION=\"$edition\"" >> config/includes.chroot/etc/aegis/build.env
  for a in "${ARCHES[@]}"; do build_one "$a" "$edition"; done
done

echo
echo "==> Done. ISOs:"
ls -1 aegis-*-*.iso 2>/dev/null || true
echo "    Test with QEMU (docs/BUILD.md), then dd to USB (scripts/write-usb.sh)."
